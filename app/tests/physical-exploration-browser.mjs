import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {preview} from 'vite';
const server=await preview({preview:{port:0,host:'127.0.0.1'},logLevel:'error'});
let browser;
try{
 browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-webgl']});
 const page=await browser.newPage();
 await page.goto(server.resolvedUrls.local[0],{waitUntil:'domcontentloaded'});

 await page.getByRole('button',{name:'English',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[data-testid="selected-potential"]')?.dataset.voltage!=='');
 const value=async()=>Number(await page.getByTestId('selected-potential').getAttribute('data-voltage'));
 const original=await value();
 await page.getByText('More settings and model details',{exact:true}).click();
 await page.getByRole('combobox',{name:'Second current source',exact:true}).selectOption('on');
 assert.ok(Math.abs(await value()-2*original)<1e-10);
 const q=page.getByRole('spinbutton',{name:'Second source strength nA·m',exact:true});
 await q.fill('-10');await q.press('Enter');
 assert.ok(Math.abs(await value())<1e-10);
 await page.getByRole('combobox',{name:'Second current source',exact:true}).selectOption('off');
 await page.getByRole('combobox',{name:'Skull conductivity',exact:true}).selectOption('mne-four-layer-sphere-ras-v1-skull-0.008');
 await page.waitForFunction(()=>document.querySelector('[data-testid="physical-field"]')?.dataset.modelId?.endsWith('0.008'));
 assert.ok(Math.abs(await value()-original)>1e-4);
 const position=await page.getByTestId('physical-field').getAttribute('data-electrode-position');
 await page.getByRole('checkbox',{name:'Drag electrodes along the scalp',exact:true}).check();
 await page.getByTestId('physical-field').scrollIntoViewIfNeeded();
 const point=await page.evaluate(()=>window.__headPhysics.sensor('Cz'));
 await page.mouse.move(point.x,point.y);await page.mouse.down();await page.mouse.move(point.x+45,point.y+30,{steps:8});await page.mouse.up();
 await page.waitForFunction(old=>document.querySelector('[data-testid="physical-field"]')?.dataset.electrodePosition!==old,position);
 assert.notEqual(await page.getByTestId('physical-field').getAttribute('data-electrode-position'),position);
 await page.getByRole('combobox',{name:'Source time course',exact:true}).selectOption('pulse');
 await page.waitForFunction(()=>document.querySelector('[data-testid="physical-field"]')?.dataset.timeMs==='600');
 const pulse=await value();
 await page.getByRole('button',{name:'Advanced labs',exact:true}).click();
 await page.getByRole('button',{name:/^Signal analysis/}).click();
 await page.getByTestId('eeg-summary').waitFor();
 const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Export JSON',exact:true}).click();
 const download=await downloadEvent,stream=await download.createReadStream();let text='';
 for await(const chunk of stream)text+=chunk.toString();
 const rec=JSON.parse(text),i=rec.channels.findIndex(c=>c.label==='Cz');
 assert.equal(rec.forwardModelId,'mne-four-layer-sphere-ras-v1-skull-0.008');
 assert.ok(Math.abs(rec.dataUv[i][rec.timesMs.indexOf(600)]-pulse)<1e-10);
 assert.ok(rec.dataUv[i].every((v,j)=>rec.timesMs[j]>=500&&rec.timesMs[j]<=700||v===0));
 assert.equal(rec.events[0].tMs,500);assert.equal(rec.observation.rawTimeMs,600);
 assert.ok(Object.hasOwn(rec.sourceSnapshot.electrodeVertices,'Cz'));
 await page.getByRole('tab',{name:'Topography',exact:true}).click();
 assert.equal(await page.getByTestId('topography-observation').getAttribute('data-time-ms'),'600');
 console.log('Dual-source cancellation, conductivity-specific solve, actual scalp-constrained sensor drag and defined source pulse → shared Raw PASS');
}finally{await browser?.close();await server.httpServer.close();}
