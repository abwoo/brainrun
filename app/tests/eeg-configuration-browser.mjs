import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {preview} from 'vite';
const server=await preview({preview:{port:0,host:'127.0.0.1'},logLevel:'error'});
let browser;
try{
 browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-webgl']});
 const page=await browser.newPage();
 await page.goto(server.resolvedUrls.local[0]+'#advanced',{waitUntil:'domcontentloaded'});
 await page.getByRole('button',{name:'English',exact:true}).click();
 await page.locator('button[data-mode="eeg"]').click();
 await page.locator('#eeg-duration').selectOption('2000');
 await page.locator('#eeg-montage').selectOption('10-10');
 await page.locator('#eeg-seed').fill('17');
 await page.getByRole('button',{name:'Run experiment',exact:true}).click();
 await page.getByTestId('eeg-summary').waitFor({timeout:30000});
 const first=await page.getByTestId('eeg-summary').textContent();
 await page.locator('#eeg-montage').selectOption('10-05');
 assert.equal(await page.getByTestId('active-recording').getAttribute('data-montage'),'10-10');
 assert.equal(await page.getByTestId('configuration-status').getAttribute('data-pending'),'true');
 assert.equal(await page.getByTestId('eeg-summary').textContent(),first);
 await page.locator('button[data-mode="play"]').click();
 await page.locator('button[data-mode="eeg"]').click();
 assert.equal(await page.locator('#eeg-montage').inputValue(),'10-05','pending draft survives navigation');
 assert.equal(await page.locator('#eeg-seed').inputValue(),'17');
 assert.equal(await page.getByTestId('active-recording').getAttribute('data-montage'),'10-10');
 await page.locator('#eeg-reference').selectOption('electrode');
 await page.locator('#eeg-reference-electrode').selectOption('Cz');
 assert.equal(await page.getByTestId('active-recording').getAttribute('data-reference'),'electrode');
 const ready=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export JSON',exact:true}).click();
 const download=await ready,stream=await download.createReadStream();let text='';
 for await(const chunk of stream)text+=chunk.toString();
 const rec=JSON.parse(text);
 assert.equal(rec.montage,'10-10');assert.equal(rec.seed,17);
 assert.deepEqual(rec.reference,{mode:'electrode',label:'Cz'});
 assert.deepEqual(rec.experiment.parameters.reference,rec.reference);
 assert.ok(rec.dataRevision>=1);assert.equal(rec.epochs,null);
 assert.ok(rec.dataUv[rec.channels.findIndex(c=>c.label==='Cz')].every(v=>v===0));
 await page.locator('button[data-mode="play"]').click();
 await page.locator('button[data-mode="eeg"]').click();
 assert.equal(await page.locator('#eeg-reference').inputValue(),'electrode');
 assert.equal(await page.locator('#eeg-reference-electrode').inputValue(),'Cz');
 console.log('EEG configuration: pending vs active, navigation, actual reference values and export lineage PASS');
}finally{await browser?.close();await server.httpServer.close();}
