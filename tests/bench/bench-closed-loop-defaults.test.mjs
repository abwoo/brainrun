/** 把 250 ms 采样线性插值成 1 ms 步长的 E 数组（76 节点；除节点 0 外其余节点取常数，不影响控制器读数）。 */
function buildTrace(samples) {
  const e = new Float64Array(76);
  e.fill(0.015);
  const at = (tMs) => {
    if (tMs <= 250) return samples[0];
    const pos = tMs / 250 - 1, lo = Math.floor(pos), hi = Math.min(samples.length - 1, lo + 1);
    return samples[lo] + (samples[hi] - samples[lo]) * (pos - lo);
  };
  return (tMs) => { e[0] = at(tMs); return e; };
}

function runController(trace, threshold, amplitude) {
  const fb = new NativeFeedback({
    node: 0, feature: 'instant', threshold, amplitude, durationMs: 100,
    periodMs: 1000, windowMs: 1000, cooldownMs: 500, delayMs: 0, maxTriggers: 100,
  }, 76, 0);
  let count = 0;
  const traceAt = buildTrace(trace);
  for (let t = 1; t <= 60000; t++) {
    if (fb.afterStep(t, traceAt(t))) count++;
  }
  return count;
}

test('current closed-loop defaults trigger a few times per minute on real spontaneous E', () => {
  const d = BENCH_SETTINGS_DEFAULTS;
  const c0 = runController(TRACE_SEED0, d.clThreshold, d.clAmplitude);
  const c7 = runController(TRACE_SEED7, d.clThreshold, d.clAmplitude);
  // 60 次评估里触发几次（不是 0 次，也不是每评必触的风暴）。
  assert.ok(c0 >= 3 && c0 <= 15, `seed 0 triggers should be a few per minute, got ${c0}`);
  assert.ok(c7 >= 3 && c7 <= 15, `seed 7 triggers should be a few per minute, got ${c7}`);
});

test('old closed-loop defaults (threshold 0.5) never trigger on the same traces', () => {
  assert.equal(runController(TRACE_SEED0, 0.5, 1), 0);
  assert.equal(runController(TRACE_SEED7, 0.5, 1), 0);
});
